//! Real-model MusiCNN *aggregation* parity: reuses the per-patch model
//! outputs the prior `musicnn_compute.rs` slice already captured from the
//! pinned upstream `musicnn_onnx.py` (cosine-parity against
//! `kima_ml::musicnn::MusicnnCompute` established there). This test does
//! NOT re-run ONNX or Essentia; it applies `kima_ml::musicnn::aggregate` to
//! those already-verified real per-patch arrays and compares the result to
//! a separately generated reference that applies the pinned upstream
//! `analyzer.py`'s own `_extract_ml_features`/`positive_prob` formula
//! (transcribed verbatim, not reimplemented differently) to the same
//! arrays. This is the per-track reduction-math parity gate, layered on top
//! of the already-established ONNX parity, not a repeat of it.
use std::collections::BTreeMap;

use kima_ml::musicnn::{MusicnnAggregate, MusicnnPatchOutputs, aggregate_patches};
use kima_ml::onnx::MusiCnnHead;

fn floats(path: &std::path::Path) -> Vec<f32> {
    let bytes = std::fs::read(path)
        .unwrap_or_else(|e| panic!("explicit reference prerequisite {}: {e}", path.display()));
    assert_eq!(
        bytes.len() % 4,
        0,
        "{}: not a multiple of 4 bytes",
        path.display()
    );
    bytes
        .chunks_exact(4)
        .map(|b| f32::from_le_bytes(b.try_into().unwrap()))
        .collect()
}

fn rows<const N: usize>(flat: Vec<f32>) -> Vec<[f32; N]> {
    assert_eq!(flat.len() % N, 0);
    flat.chunks_exact(N)
        .map(|c| c.try_into().unwrap())
        .collect()
}

fn head_name(head: MusiCnnHead) -> &'static str {
    head.basename().split("-msd-").next().unwrap()
}

/// `patches/aggregate-reference.json`'s per-case object, read without a JSON
/// crate dependency: every field here is a plain f64 the pinned-formula
/// reference script already rounded to 3 decimals.
fn expected(dir: &std::path::Path, case: &str) -> MusicnnAggregate {
    let text = std::fs::read_to_string(dir.join("aggregate-reference.json")).unwrap_or_else(|e| {
        panic!(
            "explicit prerequisite: aggregate-reference.json missing at {}: {e}",
            dir.display()
        )
    });
    let value: serde_json::Value = serde_json::from_str(&text).expect("valid reference JSON");
    let case = &value["cases"][case];
    let field = |name: &str| {
        case[name]
            .as_f64()
            .unwrap_or_else(|| panic!("missing {name}")) as f32
    };
    MusicnnAggregate {
        mood_happy: field("moodHappy"),
        mood_sad: field("moodSad"),
        mood_relaxed: field("moodRelaxed"),
        mood_aggressive: field("moodAggressive"),
        mood_party: field("moodParty"),
        mood_acoustic: field("moodAcoustic"),
        mood_electronic: field("moodElectronic"),
        danceability: field("danceability"),
        valence: field("valence"),
        arousal: field("arousal"),
    }
}

fn assert_close(name: &str, actual: f32, expected: f32) {
    let diff = (actual - expected).abs();
    assert!(
        diff <= 1e-6,
        "{name}: actual {actual} expected {expected} diff {diff}"
    );
}

/// Real model outputs, pinned-formula reference: both generated by
/// `~/.hermes/cache/scratch/m4-musicnn-compute/reference.py` (per-patch
/// arrays) and `reference_aggregate.py` (transcribed upstream reduction).
/// No ONNX runtime or private models are loaded by this test itself.
#[test]
#[ignore = "requires the independently generated private upstream aggregation reference"]
fn private_pinned_upstream_aggregate_parity() {
    let reference = std::env::var_os("KIMA_MUSICNN_REFERENCE_DIR")
        .expect("explicit prerequisite: KIMA_MUSICNN_REFERENCE_DIR from pinned upstream generator");
    let reference = std::path::Path::new(&reference);
    for (case, patch_count) in [("period17", 3), ("gate30", 19), ("chirp90", 59)] {
        let dir = reference.join(case);
        let embeddings = rows::<200>(floats(&dir.join("musicnn.f32")));
        assert_eq!(
            embeddings.len(),
            patch_count,
            "{case}: embedding patch count"
        );
        let heads: BTreeMap<_, _> = MusiCnnHead::all()
            .iter()
            .map(|&head| {
                let values = rows::<2>(floats(&dir.join(format!("{}.f32", head_name(head)))));
                assert_eq!(
                    values.len(),
                    patch_count,
                    "{case}/{head:?}: head patch count"
                );
                (head, values)
            })
            .collect();
        let patches = MusicnnPatchOutputs::try_new(embeddings, heads).unwrap();
        let actual = aggregate_patches(&patches);
        let want = expected(reference, case);
        assert_close(
            &format!("{case}/moodHappy"),
            actual.mood_happy,
            want.mood_happy,
        );
        assert_close(&format!("{case}/moodSad"), actual.mood_sad, want.mood_sad);
        assert_close(
            &format!("{case}/moodRelaxed"),
            actual.mood_relaxed,
            want.mood_relaxed,
        );
        assert_close(
            &format!("{case}/moodAggressive"),
            actual.mood_aggressive,
            want.mood_aggressive,
        );
        assert_close(
            &format!("{case}/moodParty"),
            actual.mood_party,
            want.mood_party,
        );
        assert_close(
            &format!("{case}/moodAcoustic"),
            actual.mood_acoustic,
            want.mood_acoustic,
        );
        assert_close(
            &format!("{case}/moodElectronic"),
            actual.mood_electronic,
            want.mood_electronic,
        );
        assert_close(
            &format!("{case}/danceability"),
            actual.danceability,
            want.danceability,
        );
        assert_close(&format!("{case}/valence"), actual.valence, want.valence);
        assert_close(&format!("{case}/arousal"), actual.arousal, want.arousal);
        println!("AGGREGATE PARITY case={case} patches={patch_count} ok");
    }
}
