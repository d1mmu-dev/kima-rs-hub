// Generates crates/kima-web/src/icons_data.rs from the lucide-react icon set (ISC licence, see
// crates/kima-web/assets/NOTICE.md). A DEV-TIME step; the output is checked in.
//   node tools/gen-kima-web-icons.mjs          write the file
//   node tools/gen-kima-web-icons.mjs --check  exit 1 if the checked-in file is stale
// Add a name to ICONS (lucide's kebab-case file name) and re-run when a view needs another icon.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS = ['arrow-left', 'audio-lines', 'bell', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'chevron-up', 'circle-alert', 'compass',
  'download', 'ellipsis', 'eye', 'eye-off', 'file-music', 'globe', 'grip-vertical', 'heart', 'history', 'house', 'info', 'library', 'link-2', 'list-music', 'list-plus',
  'lock', 'maximize-2', 'menu', 'mic-vocal', 'music', 'pause', 'pencil', 'play', 'plus', 'power', 'refresh-cw', 'repeat', 'repeat-1', 'rotate-ccw', 'rotate-cw', 'search',
  'settings', 'share-2', 'shuffle', 'skip-back', 'skip-forward', 'sliders-horizontal', 'sparkles', 'timer', 'trash-2', 'user', 'volume-2', 'volume-x', 'x'];

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const legacy = process.env.LEGACY_COPY || path.join(os.homedir(), '.hermes/cache/scratch/m9-legacy-ref');
const dir = path.join(legacy, 'node_modules/lucide-react/dist/esm/icons');
let out = `// Generated by tools/gen-kima-web-icons.mjs from lucide-react (ISC): do not edit.
// name -> list of (svg tag, attributes) in the 24x24 viewBox.

pub type Shape = (&'static str, &'static [(&'static str, &'static str)]);

pub fn shapes(name: &str) -> Option<&'static [Shape]> {
    Some(match name {
`;
for (const name of ICONS) {
  const src = fs.readFileSync(path.join(dir, name + '.js'), 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst /);
  const nodes = eval(m[1]);
  out += `        "${name}" => &[\n`;
  for (const [tag, attrs] of nodes) {
    const kv = Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `("${k}", ${JSON.stringify(String(v))})`).join(', ');
    out += `            ("${tag}", &[${kv}]),\n`;
  }
  out += '        ],\n';
}
out += '        _ => return None,\n    })\n}\n';
const target = path.join(root, 'crates/kima-web/src/icons_data.rs');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
  console.log(same ? 'icons_data.rs is up to date' : 'icons_data.rs is STALE');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${ICONS.length} icons`);
