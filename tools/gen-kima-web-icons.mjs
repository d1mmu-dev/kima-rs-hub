// Generates crates/kima-web/src/icons_data.rs from the lucide-react icon set (ISC licence, see
// crates/kima-web/assets/NOTICE.md). A DEV-TIME step; the output is checked in.
//   node tools/gen-kima-web-icons.mjs          write the file
//   node tools/gen-kima-web-icons.mjs --check  exit 1 if the checked-in file is stale
//   node tools/gen-kima-web-icons.mjs --source print the lucide-react version, integrity and directory, then exit
// Add a name to ICONS (lucide's kebab-case file name) and re-run when a view needs another icon.
// The generated header records the lucide-react version and npm integrity; the installed package must have exactly
// the version the reference copy's package-lock.json resolves (otherwise exit 2), so --check also catches a moved
// upstream lucide-react.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { toolsEnv } from './tools-env.mjs';

const ICONS = ['arrow-left', 'audio-lines', 'audio-waveform', 'bell', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'chevron-up', 'circle-alert', 'compass',
  'download', 'ellipsis', 'eye', 'eye-off', 'file-music', 'globe', 'grip-vertical', 'heart', 'history', 'house', 'info', 'library', 'link-2', 'list-music', 'list-plus', 'loader-circle',
  'lock', 'maximize-2', 'menu', 'mic-vocal', 'music', 'orbit', 'pause', 'pencil', 'play', 'plus', 'power', 'radio', 'refresh-cw', 'repeat', 'repeat-1', 'rotate-ccw', 'rotate-cw', 'save', 'search',
  'settings', 'share-2', 'shuffle', 'skip-back', 'skip-forward', 'sliders-horizontal', 'sparkles', 'timer', 'trash-2', 'user', 'volume-2', 'volume-x', 'x'];

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
// lucide-react comes from the isolated reference copy's install (`tools/prepare-kima-hub-reference.sh --install`,
// which never writes into the external kima-hub checkout): KIMA_REFERENCE_FRONTEND (environment, as printed by that
// script), else <KIMA_REFERENCE_COPY>/frontend with KIMA_REFERENCE_COPY from the environment or the private tools
// config (tools/tools-env.mjs), default the script's own default copy.
const frontend = process.env.KIMA_REFERENCE_FRONTEND
  || path.join(toolsEnv('KIMA_REFERENCE_COPY') || path.join(process.env.XDG_CACHE_HOME || path.join(os.homedir(), '.cache'), 'kima-rs/kima-hub-reference'), 'frontend');
const pkgDir = path.join(frontend, 'node_modules/lucide-react');
function fail(message) {
  console.error(message);
  process.exit(2);
}
let locked;
let installed;
try {
  locked = JSON.parse(fs.readFileSync(path.join(frontend, 'package-lock.json'), 'utf8')).packages['node_modules/lucide-react'];
} catch (e) {
  fail(`cannot read lucide-react from ${frontend}/package-lock.json: ${e.message}`);
}
if (!locked || !locked.version || !locked.integrity) fail(`${frontend}/package-lock.json has no lucide-react version/integrity`);
try {
  installed = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
} catch {
  fail(`lucide-react is not installed in ${pkgDir}: run tools/prepare-kima-hub-reference.sh --install`);
}
if (installed !== locked.version) fail(`installed lucide-react ${installed} differs from the lockfile's ${locked.version} in ${frontend}`);
if (process.argv.includes('--source')) {
  console.log(`lucide-react ${locked.version} ${locked.integrity} ${pkgDir}`);
  process.exit(0);
}
const dir = path.join(pkgDir, 'dist/esm/icons');
let out = `// Generated by tools/gen-kima-web-icons.mjs from lucide-react ${locked.version} (npm ${locked.integrity}; ISC): do not edit.
// name -> list of (svg tag, attributes) in the 24x24 viewBox.

pub type Shape = (&'static str, &'static [(&'static str, &'static str)]);

pub fn shapes(name: &str) -> Option<&'static [Shape]> {
    Some(match name {
`;
for (const name of ICONS) {
  const src = fs.readFileSync(path.join(dir, name + '.js'), 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst /);
  const nodes = eval(m[1]);
  out += `        "${name}" => &[\n`;
  for (const [tag, attrs] of nodes) {
    const kv = Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `("${k}", ${JSON.stringify(String(v))})`).join(', ');
    out += `            ("${tag}", &[${kv}]),\n`;
  }
  out += '        ],\n';
}
out += '        _ => return None,\n    })\n}\n';
const target = path.join(root, 'crates/kima-web/src/icons_data.rs');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
  console.log(same ? 'icons_data.rs is up to date' : 'icons_data.rs is STALE');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${ICONS.length} icons`);
